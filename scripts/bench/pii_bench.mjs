const stats = {};
const misses = [];
for (const [text, name, labels] of CASES) {
  const { anonymizedText } = anonymizePII(text, name);
  for (const [pii, cat] of labels) {
    stats[cat] ??= { total: 0, hit: 0 };
    stats[cat].total++;
    if (!anonymizedText.includes(pii)) stats[cat].hit++;
    else misses.push(`[${cat}] "${pii}"  ←  ${anonymizedText}`);
  }
}

let tot = 0, hit = 0;
console.log('카테고리\t검출/전체\t검출률');
for (const [cat, s] of Object.entries(stats)) {
  tot += s.total; hit += s.hit;
  console.log(`${cat}\t${s.hit}/${s.total}\t${((s.hit / s.total) * 100).toFixed(0)}%`);
}
console.log(`전체\t${hit}/${tot}\t${((hit / tot) * 100).toFixed(1)}%`);

const std = CASES.slice(0, 10).flatMap(c => c[2]).length;
const stdMiss = misses.filter(m => CASES.slice(0, 10).some(c => c[2].some(([p]) => m.includes(`"${p}"`)))).length;
console.log(`\n교과서 표기(1~10번) ${std - stdMiss}/${std} / 변형 표기(11~38번) ${(hit) - (std - stdMiss)}/${tot - std}`);

console.log('\n── 놓친 항목 ──');
misses.forEach(m => console.log(m));

console.log('\n── 오탐 (개인정보 없는 문장인데 바뀜) ──');
